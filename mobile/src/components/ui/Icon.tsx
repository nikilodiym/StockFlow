/** Consistent line icons drawn in native views, with no fonts or extra packages. */
export default function Icon({ name, size = 22, color = '#1F2823', strokeWidth = 1.8 }: Props) {
    const scale = size / 24;
    return <View accessibilityLabel={name} style={{ width: size, height: size }}>
        {drawings[name].map(([x1,y1,x2,y2,baseWidth = 1.8], index) => {
            const lineWidth = baseWidth * strokeWidth / 1.8;
            const length = Math.max(Math.hypot(x2-x1,y2-y1),lineWidth);
            return <View key={`${name}-${index}`} style={{
                position:'absolute',left:((x1+x2)/2-length/2)*scale,top:((y1+y2)/2-lineWidth/2)*scale,
                width:length*scale,height:lineWidth*scale,borderRadius:lineWidth*scale/2,
                backgroundColor:color,transform:[{rotate:`${Math.atan2(y2-y1,x2-x1)}rad`}],
            }} />;
        })}
    </View>;
}
